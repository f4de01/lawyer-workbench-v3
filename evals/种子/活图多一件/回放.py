"""种子「活图多一件」：领域目录是律师本机的活图，活图上有一件出厂种子与两份视图里都没有的节点。

用法：python 回放.py <工作区>    （由 scripts/skill-eval.py 调，也可手跑）

路由拿到的领域图必须是活图，不是包内的出厂种子（ADR-0019、#92）。要把这件事测出来，
活图就得与种子长得不一样：这里让它多一个节点，摆在模块「申请确认债权」下（种子里那个模块
只有两件，本案两件都办完了）。两条路因此给出两个不同的答案：

    读活图 → 那个模块还差一件，问 3 命中，下一句是活图上那一件
    读种子 → 那个模块一件不缺，问 3 落空、掉到问 4，答的是别的模块里的节点

**活图那一改落在最后一次写案件图之后**，所以工作区里两份视图的「前方」是改之前算的，
里面没有那一件（视图只在写案件图时重算，活图改了不会回头刷新它）。这一步是刻意的：
不这样摆，模型光读 `图视图.md` 就能答对，这条用例就测不出它有没有真去打开领域图。
律师的活图本来就会在别的案子里长出新节点，本案的视图不跟着变，这就是那个形状。

多出来的那一件按 ADR-0019 律师侧那条路进的活图（节点确认之后问一次归属，不给时限句），
时限句是律师后来自己在活图上补的（引擎的 set-time-limit，--kind domain）。给它一句时限，
是为了同一条用例顺带核 #71 那条「写往下的路之前逐个查时限」在活图上照样成立：这句话只在
活图上有，出厂种子与两份视图里一个字都没有。

工作区里没有任何案件内容：文书与审查报告都是合成的几行字，当事人一律写甲乙丙。
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[2] / "共用"))
import 基线  # noqa: E402
import 回放助手 as 助手  # noqa: E402

领域名 = "破产"
活图独有 = "裁定确认职工债权的申请"       # 出厂种子与两份视图里都没有它：路由答出它，就是真读了活图
活图独有的id = "n-queren-zhigong"
活图独有的模块 = "申请确认债权"           # 种子里这个模块只有下面那两件
活图独有的时限 = "自职工债权表公示之日起 15 日内提请法院裁定确认（活图，律师补）"
先办完的 = ("裁定确认无异议债权的申请", "裁定补充确认债权的申请")  # 领域图带入，办完之后这块只差活图那一件


def main(workspace: str) -> int:
    ws = pathlib.Path(workspace)
    助手.用活图(ws, 领域名)      # 往后的起手与写图都指这份活图，工作区 AGENTS.md 记的也是它
    助手.起手(ws, "--empty")
    助手.办完(ws, 先办完的[0], "无异议债权这份可以了")
    助手.办完(ws, 先办完的[1], "补充确认这份也可以了")
    # 到这里为止案件图不再变，两份视图也就定在这一刻了。活图往后长出来的东西，视图看不见。
    助手.领域图引擎(ws, "add-node", "--module", 活图独有的模块, "--title", 活图独有,
                    "--id", 活图独有的id)
    助手.领域图引擎(ws, "set-time-limit", "--node", 活图独有的id, "--time-limit", 活图独有的时限)
    基线.写基线(ws)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))
